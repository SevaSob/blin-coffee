def parse_variants(price_str, desc):
    """
    Пытается вытащить варианты из пары (строка цены, строка объёмов).
    Возвращает [(name, price), ...] или None.
    Пример: '220 / 260 ₽' + '350 / 450 мл' → [('350 мл', 220), ('450 мл', 260)]
    """
    # убираем ₽ и всё, что не цифры/слэши/пробелы
    prices_raw = price_str.replace('₽', '')
    prices = [int(x) for x in re.findall(r'\d+', prices_raw)]

    # ищем объёмы в описании: '350 / 450 мл' или '0,5 / 0,7 л'
    desc_low = desc.lower()
    volumes = re.findall(r'(\d+(?:[.,]\d+)?)\s*(мл|л)\b', desc_low)

    # нормализуем единицы: л → мл
    norm_volumes = []
    for v, unit in volumes:
        num = v.replace(',', '.')
        if unit == 'л':
            num_float = float(num) * 1000
            if num_float.is_integer():
                norm_volumes.append(f'{int(num_float)} мл')
            else:
                norm_volumes.append(f'{num_float} мл')
        else:
            norm_volumes.append(f'{num} мл')

    # если цен и объёмов одинаково и их больше одного — делаем варианты
    if len(prices) == len(norm_volumes) and len(prices) >= 2:
        return list(zip(norm_volumes, prices))

    # одиночная цена + одиночный объём
    if len(prices) == 1 and len(norm_volumes) == 1:
        return [(norm_volumes[0], prices[0])]

    return None


def make_tree(items, parent=None):
    """Рекурсивно создаёт категории, возвращает {full_path: Category}."""
    result = {}
    for idx, (name, icon, children) in enumerate(items):
        c = Category(name=name, icon=icon, parent=parent, sort_order=idx)
        db.session.add(c)
        db.session.flush()
        path = c.full_name
        result[path] = c
        if children:
            result.update(make_tree(children, parent=c))
    return result


def run():
    with app.app_context():
        db.create_all()

        # ---- чистка (порядок важен из-за FK) ----
        Favorite.query.delete()
        ProductVariant.query.delete()
        Product.query.delete()
        Category.query.delete()
        Promotion.query.delete()
        db.session.commit()
        print('🧹 База очищена')

        # ---- категории ----
        cat_map = make_tree(CATEGORIES_TREE)
        db.session.commit()
        print(f'✅ Категорий: {len(cat_map)}')

        # ---- системная «Без категории» ----
        if not Category.query.filter_by(is_system=True).first():
            db.session.add(Category(name='Без категории', icon='📦',
                                    is_system=True, sort_order=9999))
            db.session.commit()

        # ---- товары + варианты ----
        total_products = 0
        total_variants = 0
        for path, items in MENU.items():
            cat = cat_map.get(path)
            if not cat:
                print(f'⚠️  Не найдена категория: {path}')
                continue
            for name, price, desc in items:
                p = Product(name=name, price=price, description=desc, category_id=cat.id)
                db.session.add(p)
                db.session.flush()

                variants = parse_variants(price, desc)
                if variants and len(variants) > 1:
                    for i, (vname, vprice) in enumerate(variants):
                        db.session.add(ProductVariant(
                            product_id=p.id, name=vname,
                            price=vprice, sort_order=i
                        ))
                        total_variants += 1
                total_products += 1
        db.session.commit()
        print(f'✅ Товаров: {total_products}, вариантов: {total_variants}')

        # ---- акции ----
        for title, desc in PROMOTIONS:
            db.session.add(Promotion(title=title, description=desc))
        db.session.commit()
        print(f'✅ Акций: {len(PROMOTIONS)}')

        # ---- админ ----
        if not User.query.filter_by(username='admin').first():
            admin = User(username='admin', is_admin=True, show_admin_counters=True)
            admin.set_password('admin')
            db.session.add(admin)
            db.session.commit()
            print('✅ Админ: admin / admin')
        else:
            print('ℹ️  Админ уже существует')

        print('\n🎉 Готово. Запускай: python app.py')


if __name__ == '__main__':
    run()